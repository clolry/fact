// Get all templates for the UI
function getRecurringTemplates() {
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  const sh = ss.getSheetByName('Recurring_Templates');
  if (!sh || sh.getLastRow() < 2) return [];
  
  const data = sh.getRange(2, 1, sh.getLastRow()-1, 7).getValues();
  return data.map(r => ({
    id: r[0], title: r[1], type: r[2], freq: r[3], 
    subtasks: r[4], nextDate: r[5] ? new Date(r[5]).toISOString().split('T')[0] : '', owner: r[6]
  }));
}

// Save or Update a Template
function saveRecurringTemplate(form) {
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  let sh = ss.getSheetByName('Recurring_Templates');
  if (!sh) {
    sh = ss.insertSheet('Recurring_Templates');
    sh.appendRow(['ID', 'Title', 'Type', 'Frequency', 'SubTasks_JSON', 'Next_Date', 'Owner']);
  }
  
  const id = form.id || 'REC-' + Date.now();
  const subtasksJSON = JSON.stringify(form.subtasks || []); // Store subtasks as JSON string
  const rowData = [id, form.title, form.type, form.freq, subtasksJSON, form.nextDate, form.owner];
  
  const data = sh.getDataRange().getValues();
  let found = false;
  
  for (let i = 1; i < data.length; i++) {
    if (String(data[i][0]) === String(id)) {
      sh.getRange(i + 1, 1, 1, 7).setValues([rowData]);
      found = true;
      break;
    }
  }
  
  if (!found) sh.appendRow(rowData);
  return { success: true };
}

// Delete a Template
function deleteRecurringTemplate(id) {
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  const sh = ss.getSheetByName('Recurring_Templates');
  const data = sh.getDataRange().getValues();
  for (let i = 1; i < data.length; i++) {
    if (String(data[i][0]) === String(id)) {
      sh.deleteRow(i + 1);
      break;
    }
  }
  return { success: true };
}

