// THE GENERATOR: Run this on a Daily Trigger
function generateRecurringTasks() {
  // PERF-05: Note - This function currently uses saveItem() inside a loop, which does individual
  // sheet read/writes. In the future, this should be refactored to gather all new tasks/subtasks
  // and append/batch write them to their respective sheets in a single operation.
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  const sh = ss.getSheetByName('Recurring_Templates');
  if (!sh || sh.getLastRow() < 2) return;
  
  const data = sh.getRange(2, 1, sh.getLastRow()-1, 7).getValues();
  const today = new Date();
  today.setHours(0,0,0,0);
  
  data.forEach((r, i) => {
    const nextDate = new Date(r[5]);
    nextDate.setHours(0,0,0,0);
    
    // If Next Date is Today or Past
    if (nextDate <= today) {
      
      // 1. Create Main Task/Project using saveItem
      // We leave ID blank so the system generates a standard ID (e.g. ITEM-1050)
      const parentResult = saveItem({
        ID: '', 
        Title: r[1], 
        Type: r[2], 
        Owner: r[6], 
        Status: 'To Do', 
        DueDate: r[5], 
        Desc: 'Auto-generated recurring task.'
      });
      
      // Capture the ID correctly generated by the system
      const parentId = parentResult.id; 
      
      // 2. Create Sub-Tasks
      if (r[4] && parentId) {
        try {
          const subs = JSON.parse(r[4]);
          subs.forEach((sub) => {
             // Calculate Offset Date
             let subDate = new Date(r[5]); // Start with Parent Due Date
             const offset = parseInt(sub.offset) || 0;
             subDate.setDate(subDate.getDate() + offset); // Add offset days
             
             const subDateStr = subDate.toISOString().split('T')[0];

             // Create Sub-task linked to the new Parent ID
             saveItem({
               ID: '', 
               Title: sub.title, 
               Type: 'Sub-task', 
               ParentID: parentId, 
               Owner: r[6], 
               Status: 'To Do', 
               DueDate: subDateStr
             });
          });
        } catch(e) { console.error('JSON Error', e); }
      }
      
      // 3. Calculate New Next Date
      let newDate = new Date(nextDate);
      if (r[3] === 'Daily') newDate.setDate(newDate.getDate() + 1);
      if (r[3] === 'Weekly') newDate.setDate(newDate.getDate() + 7);
      if (r[3] === 'Monthly') newDate.setMonth(newDate.getMonth() + 1);
      if (r[3] === 'Yearly') newDate.setFullYear(newDate.getFullYear() + 1);
      
      // Update Template with new date
      sh.getRange(i + 2, 6).setValue(newDate);
    }
  });
}
