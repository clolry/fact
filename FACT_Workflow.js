// Get all Type Templates for UI
function getTypeTemplates() {
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  const sh = ss.getSheetByName('Type_Templates');
  if (!sh || sh.getLastRow() < 2) return [];
  
  // Columns: [Type, SubTasks_JSON]
  const data = sh.getRange(2, 1, sh.getLastRow()-1, 2).getValues();
  return data.map(r => ({ type: r[0], subtasks: r[1] }));
}

// Save a Type Template
function saveTypeTemplate(type, subtasks) {
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  let sh = ss.getSheetByName('Type_Templates');
  if (!sh) {
    sh = ss.insertSheet('Type_Templates');
    sh.appendRow(['Type', 'SubTasks_JSON']);
  }
  
  const json = JSON.stringify(subtasks || []);
  const data = sh.getDataRange().getValues();
  let found = false;
  
  // Update existing row if Type exists
  for (let i = 1; i < data.length; i++) {
    if (String(data[i][0]) === String(type)) {
      sh.getRange(i + 1, 2).setValue(json);
      found = true;
      break;
    }
  }
  
  // Or append new row
  if (!found) sh.appendRow([type, json]);
  return { success: true };
}

// HELPER: Auto-generate subtasks based on Type
function applyTypeTemplate(parentId, type, owner, dueDateStr) {
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  const sh = ss.getSheetByName('Type_Templates');
  if (!sh || sh.getLastRow() < 2) return;
  
  const data = sh.getRange(2, 1, sh.getLastRow()-1, 2).getValues();
  const template = data.find(r => r[0] === type);
  
  if (template && template[1]) {
    try {
      const subs = JSON.parse(template[1]);
      const parentDate = dueDateStr ? new Date(dueDateStr) : new Date();

      subs.forEach((sub) => {
         // Calculate Offset Date
         let subDate = new Date(parentDate);
         const offset = parseInt(sub.offset) || 0;
         subDate.setDate(subDate.getDate() + offset);
         const subDateStr = subDate.toISOString().split('T')[0];

         // Use saveItem instead of addProject
         saveItem({
           ID: '', 
           Title: sub.title, 
           Type: 'Sub-task', 
           ParentID: parentId, 
           Owner: owner, 
           Status: 'To Do', 
           DueDate: subDateStr
         });
      });
      console.log(`Applied ${type} template to ${parentId}`);
    } catch(e) { console.error('Template Error', e); }
  }
}

function getPerformanceReport(startStr, endStr, ownerFilter) {
  const ss = SpreadsheetApp.getActive();
  const tz = ss.getSpreadsheetTimeZone(); 
  
  const sheets = ['Projects', 'Tasks', 'Projects_Archive', 'Tasks_Archive'];
  let results = [];

  sheets.forEach(name => {
    const sh = ss.getSheetByName(name);
    if (!sh || sh.getLastRow() < 2) return;
    
    const data = sh.getDataRange().getValues();
    const headers = data[0] || [];
    const isProject = name.includes('Project');
    
    const statusIdx = headers.indexOf('Status') !== -1 ? headers.indexOf('Status') : 6;
    const ownerIdx = headers.indexOf('Owner') !== -1 ? headers.indexOf('Owner') : (isProject ? 3 : 4);
    let doneDateIdx = headers.indexOf('CompletedDate');
    if (doneDateIdx === -1) doneDateIdx = headers.indexOf('Completed_Date');
    if (doneDateIdx === -1) doneDateIdx = isProject ? 32 : 18;
    const dueDateIdx = headers.indexOf('DueDate') !== -1 ? headers.indexOf('DueDate') : 5;
    
    for (let i = 1; i < data.length; i++) {
      const row = data[i];
      const status = row[statusIdx];
      const rowOwner = row[ownerIdx]; 
      
      if (ownerFilter && rowOwner !== ownerFilter) continue;
      if (status !== 'Done') continue;

      let doneDate = row[doneDateIdx];
      // Fallback: If no "Done Date" recorded, use "Due Date"
      if (!doneDate || doneDate === '') doneDate = row[dueDateIdx]; 
      
      let dString = "";
      try {
         const dateObj = (doneDate instanceof Date) ? doneDate : new Date(doneDate);
         dString = Utilities.formatDate(dateObj, tz, "yyyy-MM-dd");
      } catch(e) { continue; }

      if (dString >= startStr && dString <= endStr) {
         let isLate = false;
         if (row[5]) { 
            const dueString = Utilities.formatDate(new Date(row[5]), tz, "yyyy-MM-dd");
            if (dueString < dString) isLate = true;
         }

         results.push({
           id: row[0],
           title: row[1],
           type: row[2],
           owner: rowOwner,
           completed: new Date(doneDate).toLocaleDateString(), 
           isLate: isLate
         });
      }
    }
  });
  
  return results.sort((a,b) => new Date(b.completed) - new Date(a.completed));
}

